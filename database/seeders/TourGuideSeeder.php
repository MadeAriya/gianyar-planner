                [
                    'bio' => $g['bio'],
                    'bahasa' => $g['bahasa'],
                    'spesialisasi' => $g['spesialisasi'],
                    'area_layanan' => $g['area_layanan'],
                    'tarif_per_hari' => $g['tarif_per_hari'],
                    'max_peserta' => $g['max_peserta'],
                    'pengalaman_tahun' => $g['pengalaman_tahun'],
                    'nomor_lisensi' => $g['nomor_lisensi'],
                    'foto' => $g['foto'],
                    'foto_ktp' => 'documents/ktp_demo_guide.jpg',
                    'sertifikat_lisensi' => 'documents/lisensi_demo_guide.pdf',
                    'rating_avg' => $g['rating_avg'],
                    'jumlah_ulasan' => $g['jumlah_ulasan'],
                    'jumlah_job_selesai' => $g['jumlah_job_selesai'],
                    'acceptance_rate' => $g['acceptance_rate'],
                    'status_verifikasi' => $g['status_verifikasi'],
                    'catatan_verifikasi' => $g['catatan_verifikasi'] ?? null,
                    'verified_by' => ($g['status_verifikasi'] === 'approved') ? $adminId : null,
                    'verified_at' => ($g['status_verifikasi'] === 'approved') ? now() : null,
                ]
            );

            // Seed 30 hari ke depan
            for ($d = 0; $d < 30; $d++) {
                $targetDate = $today->copy()->addDays($d)->toDateString();

                // Pola deterministik realistis
                $statusAvailability = 'tersedia';
                $bookingRef = null;

                if ($g['status_verifikasi'] !== 'approved') {
                    $statusAvailability = 'diblokir_guide';
                } else {
                    // Beberapa hari terpesan / diblokir guide
                    if (($d + $index) % 8 === 0) {
                        $statusAvailability = 'terpesan';
                        $bookingRef = 'BOOK-SEED-'.($index + 1).'-'.$d;
                    } elseif (($d + $index) % 13 === 0) {
                        $statusAvailability = 'diblokir_guide';
                    }
                }

                GuideAvailability::updateOrCreate(
                    [
                        'guide_id' => $guide->id,
                        'tanggal' => $targetDate,
                    ],
                    [
                        'status' => $statusAvailability,
                        'booking_ref' => $bookingRef,
                    ]
                );
            }
        }
    }
