    /**
     * Mengambil daftar semua key subkategori yang valid.
     *
     * @return string[]
     */
    public static function subkategoriKeys(): array
    {
        $keys = [];
        foreach (self::kategoriList() as $utama) {
            foreach (array_keys($utama['subkategori']) as $subKey) {
                $keys[] = $subKey;
            }
        }

        return $keys;
    }

    /**
     * Dapatkan label yang mudah dibaca untuk key kategori atau subkategori.
     */
    public static function kategoriLabel(string $key): string
    {
        $map = [
            'alam' => 'Wisata Alam',
            'budaya' => 'Wisata Budaya',
            'seni' => 'Seni & Kerajinan',
            'kuliner' => 'Wisata Kuliner',
            'spiritual' => 'Spiritual & Wellness',
            'petualangan' => 'Petualangan',
            'keluarga' => 'Keluarga & Satwa',
        ];

        foreach (self::kategoriList() as $katKey => $utama) {
            if ($katKey === $key) {
                return $utama['label'];
            }
            if (isset($utama['subkategori'][$key])) {
                return $utama['subkategori'][$key]['label'];
            }
        }

        return $map[$key] ?? ucfirst(str_replace('_', ' ', $key));
    }

